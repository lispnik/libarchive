#!/usr/bin/env python3
"""Generate src/ffi-archive.lisp and src/ffi-entry.lisp from libarchive's headers.

    python3 -I tools/gen-ffi.py /opt/homebrew/opt/libarchive/include src/

Every __LA_DECL becomes a cffi:defcfun named %<c-name-with-dashes>. Declarations
guarded by _WIN32 are dropped (they reference types that do not exist elsewhere).
The output is checked in; rerun this when the headers move and diff the result.
"""
import os
import re
import sys

WIN32_ONLY = {"archive_read_open_filenames_w", "archive_entry_copy_bhfi"}

# C type (qualifiers stripped, whitespace normalised) -> CFFI type.
TYPES = {
    "void": ":void",
    "int": ":int",
    "unsigned int": ":uint",
    "long": ":long",
    "unsigned long": ":ulong",
    "char": ":char",
    "size_t": ":size",
    "la_int64_t": ":int64",
    "la_ssize_t": ":ssize",
    "time_t": "time-t",
    "__LA_TIME_T": "time-t",
    "__LA_MODE_T": "mode-t",
    "mode_t": "mode-t",
    "__LA_DEV_T": "dev-t",
    "dev_t": "dev-t",
    "__LA_INO_T": ":int64",
    "char *": ":string",
    "struct archive *": "archive",
    "struct archive_entry *": "archive-entry",
}

TYPE_WORDS = {"const", "unsigned", "signed", "struct", "int", "long", "char",
              "void", "size_t", "la_int64_t", "la_ssize_t", "time_t", "wchar_t",
              "__LA_TIME_T", "__LA_MODE_T", "__LA_DEV_T", "__LA_INO_T", "mode_t",
              "dev_t", "archive", "archive_entry", "archive_acl", "stat",
              "archive_entry_linkresolver"}


def strip_comments(src):
    src = re.sub(r"/\*.*?\*/", "", src, flags=re.S)
    return re.sub(r"//[^\n]*", "", src)


def declarations(src):
    """Yield (declaration-text) for every __LA_DECL outside #define lines."""
    lines = []
    skip = False
    for line in src.splitlines():
        s = line.strip()
        if skip or s.startswith("#"):
            skip = s.endswith("\\")
            continue
        lines.append(line)
    body = "\n".join(lines)
    for m in re.finditer(r"__LA_DECL\s+(.*?);", body, flags=re.S):
        d = " ".join(m.group(1).split()).replace("__LA_DEPRECATED", "")
        yield re.sub(r"__LA_PRINTF\(.*?\)", "", d).strip()


def split_params(s):
    out, depth, cur = [], 0, ""
    for ch in s:
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
        if ch == "," and depth == 0:
            out.append(cur.strip())
            cur = ""
        else:
            cur += ch
    if cur.strip():
        out.append(cur.strip())
    return out


def lisp_type(ctype, is_return):
    t = " ".join(ctype.replace("*", " * ").split())
    stars = t.count("*")
    base = " ".join(w for w in t.split() if w not in ("const", "*"))
    if stars == 0:
        return TYPES[base]
    if stars == 1 and base == "char":
        # A returned char* that the caller must free (acl_to_text) stays a
        # pointer; const char* is a string, and a returned one is c-string
        # (types.lisp), which reads bytes that are not UTF-8 as Latin-1.
        if is_return and not ctype.strip().startswith("const"):
            return ":pointer"
        return "c-string" if is_return else ":string"
    if stars == 1 and base in ("struct archive", "struct archive_entry"):
        return TYPES[base + " *"]
    return ":pointer"


# C names that would fold onto another function's name once upcased.
RENAMES = {"archive_read_open_FILE": "archive-read-open-stdio",
           "archive_write_open_FILE": "archive-write-open-stdio"}


def lisp_name(cname):
    return RENAMES.get(cname) or cname.replace("_", "-")


def parse(decl):
    m = re.match(r"(.*?)\b(archive_\w+)\s*\((.*)\)\s*$", decl, flags=re.S)
    if not m:
        raise ValueError(decl)
    rtype, name, params = m.group(1).strip(), m.group(2), m.group(3).strip()
    args, variadic = [], False
    if params not in ("", "void"):
        for i, p in enumerate(split_params(params)):
            if p == "...":
                variadic = True
                continue
            if "(" in p:  # function pointer
                pm = re.search(r"\(\s*\*\s*(\w*)\s*\)", p)
                pname = (pm.group(1) if pm and pm.group(1) else "fn%d" % i)
                args.append((pname, ":pointer", p))
                continue
            toks = p.replace("*", " * ").split()
            pname = None
            if toks and toks[-1] not in TYPE_WORDS and toks[-1] != "*" \
                    and re.match(r"^\w+$", toks[-1]):
                pname = toks.pop()
            ctype = " ".join(toks)
            args.append((pname or "arg%d" % i, lisp_type(ctype, False), ctype))
    return name, lisp_type(rtype, True), rtype, args, variadic


def emit(decl_list, header):
    out = [";;; Generated by tools/gen-ffi.py from %s -- do not edit by hand." % header,
           ";;; Raw entry points: names are the C names with _ -> - and a % prefix.",
           ";;; `const char *' is :string as an argument (UTF-8, NIL -> NULL) and",
           ";;; c-string as a result (UTF-8, else Latin-1; NULL -> NIL); everything",
           ";;; else that is a pointer is :pointer. Nothing here is called at load time.",
           "",
           "(in-package #:libarchive)",
           ""]
    names = []
    for d in decl_list:
        name, rtype, crtype, args, variadic = parse(d)
        if name in WIN32_ONLY:
            continue
        names.append(name)
        seen = set()
        argforms = []
        for pname, ltype, _ in args:
            pn = lisp_name(pname.lstrip("_")) or "arg"
            while pn in seen:
                pn += "*"
            seen.add(pn)
            argforms.append("(%s %s)" % (pn, ltype))
        if variadic:
            argforms.append("&rest")
        out.append('(cffi:defcfun ("%s" %%%s :library libarchive) %s%s'
                   % (name, lisp_name(name), rtype,
                      "".join("\n  " + a for a in argforms)))
        out[-1] += ")"
        out.append("")
    return "\n".join(out), names


def constants(incdir):
    """Every integer #define ARCHIVE_* / AE_* in both headers, evaluated."""
    values, order = {}, []
    for header in ("archive.h", "archive_entry.h"):
        src = open(os.path.join(incdir, header)).read().replace("\\\n", " ")
        src = re.sub(r"/\*.*?\*/", "", src, flags=re.S)
        for m in re.finditer(r"^#\s*define\s+((?:ARCHIVE|AE)_[A-Z0-9_]+)[ \t]+(.+)$",
                             src, flags=re.M):
            name, expr = m.group(1), m.group(2).strip()
            if "VERSION" in name or "STRING" in name:
                continue
            expr = re.sub(r"\(\s*__LA_MODE_T\s*\)", "", expr)
            expr = re.sub(r"\b0([0-7]+)\b", r"0o\1", expr)
            expr = re.sub(r"\b[A-Z][A-Z0-9_]+\b",
                          lambda t: str(values[t.group(0)]), expr)
            try:
                values[name] = eval(expr, {"__builtins__": {}})
            except Exception:
                continue
            if isinstance(values[name], int):
                order.append(name)
    return [(n, values[n]) for n in order]


def lisp_constant(cname):
    return "+" + cname.lower().replace("_", "-") + "+"


def main(incdir, outdir):
    with open(os.path.join(outdir, "constants.lisp"), "w") as f:
        f.write(";;; Generated by tools/gen-ffi.py from archive.h and archive_entry.h --\n"
                ";;; do not edit by hand. Every integer ARCHIVE_* and AE_* macro, as a\n"
                ";;; DEFCONSTANT named after it: ARCHIVE_FILTER_GZIP -> +ARCHIVE-FILTER-GZIP+.\n\n"
                "(in-package #:libarchive)\n\n")
        consts = constants(incdir)
        for n, v in consts:
            f.write("(defconstant %s %d)\n" % (lisp_constant(n), v))
        f.write("\n(defparameter *constant-names*\n  '(")
        f.write("\n    ".join('("%s" . %s)' % (n, lisp_constant(n)) for n, _ in consts))
        f.write(")\n  \"C macro name -> Lisp constant, for the header cross-check.\")\n")
    all_names = []
    for header, out in (("archive.h", "ffi-archive.lisp"),
                        ("archive_entry.h", "ffi-entry.lisp")):
        src = strip_comments(open(os.path.join(incdir, header)).read())
        text, names = emit(list(declarations(src)), header)
        all_names += names
        with open(os.path.join(outdir, out), "w") as f:
            f.write(text)
    with open(os.path.join(outdir, "ffi-names.lisp"), "w") as f:
        f.write(";;; Generated by tools/gen-ffi.py -- every C entry point bound raw.\n\n"
                "(in-package #:libarchive)\n\n"
                "(defparameter *foreign-function-names*\n  '(")
        f.write("\n    ".join('("%s" . %%%s)' % (n, lisp_name(n)) for n in all_names))
        f.write(")\n  \"C name -> raw Lisp function, for every function bound, in header order.\")\n")
    print("%d functions" % len(all_names))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
