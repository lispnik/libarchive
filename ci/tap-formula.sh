#!/bin/sh
# Print the Homebrew formula for a release, from its SHA256SUMS.
#
#   ci/tap-formula.sh v0.2.0 > ../homebrew-tap/Formula/la.rb
#
# The tap is github.com/lispnik/homebrew-tap; commit and push it after each
# release (`brew install lispnik/tap/la').
set -eu

TAG=$1
REPO=lispnik/libarchive
SUMS=$(gh release download "$TAG" -R "$REPO" -p SHA256SUMS -O -)
sum() { echo "$SUMS" | awk -v f="la-$1.tar.gz" '$2 == f { print $1 }'; }
url() { echo "https://github.com/$REPO/releases/download/$TAG/la-$1.tar.gz"; }

for p in macos-arm64 macos-x86_64 linux-x86_64 linux-aarch64; do
    [ -n "$(sum $p)" ] || { echo "no checksum for la-$p in $TAG" >&2; exit 1; }
done

cat <<FORMULA
# Generated by ci/tap-formula.sh in $REPO; do not edit by hand.
class La < Formula
  desc "Extract, create, list and compare archives in every format libarchive handles"
  homepage "https://github.com/$REPO"
  license "MIT"

  on_macos do
    on_arm do
      url "$(url macos-arm64)"
      sha256 "$(sum macos-arm64)"
    end
    on_intel do
      url "$(url macos-x86_64)"
      sha256 "$(sum macos-x86_64)"
    end
  end

  on_linux do
    on_arm do
      url "$(url linux-aarch64)"
      sha256 "$(sum linux-aarch64)"
    end
    on_intel do
      url "$(url linux-x86_64)"
      sha256 "$(sum linux-x86_64)"
    end
  end

  def install
    bin.install "la"
    man1.install "la.1"
    zsh_completion.install "_la"
    bash_completion.install "la.bash" => "la"
  end

  test do
    assert_match "(bundled)", shell_output("#{bin}/la --version")
    (testpath/"hello.txt").write "hello"
    system bin/"la", "a", "-q", "hello.tar.gz", "hello.txt"
    assert_equal "hello.txt\\n", shell_output("#{bin}/la l hello.tar.gz")
    system bin/"la", "diff", "-q", "hello.tar.gz"
  end
end
FORMULA
